/**
 * Self-host Google Fonts: download each family's CSS (woff2) + the woff2 files
 * into public/assets/fonts/, rewrite the @font-face src to local relative paths,
 * and concatenate into public/assets/fonts/fonts.css. Run once: node download-fonts.mjs
 * Retries each request (the network to Google is flaky).
 */
import { mkdirSync, writeFileSync, existsSync } from 'fs';
const OUT = 'public/assets/fonts';
mkdirSync(OUT, { recursive: true });
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';
const sleep = ms => new Promise(r => setTimeout(r, ms));

// Families as the app uses them. Fira Sans reduced 18->3 weights (only the
// Material-typography weights are actually rendered); everything else matches
// the exact axes referenced in index.html / styles.scss.
const FAMILIES = [
  ['Fraunces',  'https://fonts.googleapis.com/css2?family=Fraunces:ital,opsz,wght,SOFT@0,9..144,300..900,0..100;1,9..144,300..900,0..100&display=swap'],
  ['Inter',     'https://fonts.googleapis.com/css2?family=Inter:opsz,wght@14..32,300..700&display=swap'],
  ['Spectral',  'https://fonts.googleapis.com/css2?family=Spectral:ital,wght@0,400;0,600;0,700;1,400&display=swap'],
  ['Caveat',    'https://fonts.googleapis.com/css2?family=Caveat:wght@400;700&display=swap'],
  ['Poppins',   'https://fonts.googleapis.com/css2?family=Poppins:wght@400;600;700&display=swap'],
  ['ComicNeue', 'https://fonts.googleapis.com/css2?family=Comic+Neue:wght@400;700&display=swap'],
  ['FiraSans',  'https://fonts.googleapis.com/css2?family=Fira+Sans:wght@400;500;700&display=swap'],
  ['MaterialSymbols', 'https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:opsz,wght,FILL,GRAD@20..48,200..700,0..1,-50..200&display=swap'],
  ['MaterialIcons',   'https://fonts.googleapis.com/icon?family=Material+Icons'],
];

async function fetchRetry(url, opts = {}, tries = 6) {
  let lastErr;
  for (let i = 0; i < tries; i++) {
    try { const r = await fetch(url, opts); if (r.ok) return r; lastErr = 'HTTP ' + r.status; }
    catch (e) { lastErr = e.message; }
    await sleep(600 * (i + 1));
  }
  throw new Error(`fetch failed (${lastErr}): ${url}`);
}

let combined = `/* Self-hosted fonts — generated by download-fonts.mjs (do not depend on Google at build/runtime). */\n`;
let totalWoff2 = 0, fails = [];
for (const [name, url] of FAMILIES) {
  process.stdout.write(`\n${name} … `);
  let css;
  try { css = await (await fetchRetry(url, { headers: { 'User-Agent': UA } })).text(); }
  catch (e) { console.log('CSS FAIL: ' + e.message); fails.push(name + ' (css)'); continue; }
  const urls = [...new Set([...css.matchAll(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+?\.woff2)\)/g)].map(m => m[1]))];
  let local = css, ok = 0;
  for (const u of urls) {
    const fn = name.toLowerCase() + '-' + u.split('/').pop();
    try {
      if (!existsSync(`${OUT}/${fn}`)) {
        const buf = Buffer.from(await (await fetchRetry(u)).arrayBuffer());
        writeFileSync(`${OUT}/${fn}`, buf);
      }
      local = local.split(u).join(`./${fn}`); ok++; totalWoff2++;
    } catch (e) { fails.push(`${name}:${fn}`); }
  }
  combined += `\n/* ===== ${name} (${ok}/${urls.length} files) ===== */\n` + local + '\n';
  console.log(`${ok}/${urls.length} woff2`);
}
writeFileSync(`${OUT}/fonts.css`, combined);
console.log(`\n${'─'.repeat(40)}\nWrote ${OUT}/fonts.css  (${totalWoff2} woff2 files)`);
if (fails.length) { console.log('FAILURES:', fails.join(', ')); process.exitCode = 1; }
else console.log('All fonts downloaded ✅');
